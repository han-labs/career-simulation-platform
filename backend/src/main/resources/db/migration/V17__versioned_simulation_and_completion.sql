CREATE TABLE public.scenario (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_scenario PRIMARY KEY,
 enterprise_id bigint NOT NULL REFERENCES public.enterprise ON DELETE RESTRICT ON UPDATE RESTRICT,
 slug varchar(120) NOT NULL CONSTRAINT uq_scenario_slug UNIQUE,
 availability_status varchar(32) NOT NULL DEFAULT 'ARCHIVED' CHECK(availability_status IN ('AVAILABLE','ARCHIVED','SUSPENDED')),
 current_version_id bigint, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0)
);
CREATE INDEX ix_scenario_enterprise ON public.scenario(enterprise_id,availability_status,id);
CREATE TABLE public.scenario_version (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_scenario_version PRIMARY KEY,
 scenario_id bigint NOT NULL REFERENCES public.scenario ON DELETE RESTRICT ON UPDATE RESTRICT,
 version_number integer NOT NULL CHECK(version_number>0), status varchar(32) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PUBLISHED')),
 title varchar(180) NOT NULL, target_role varchar(120) NOT NULL, career_track varchar(60) NOT NULL,
 summary varchar(600) NOT NULL, introduction text NOT NULL, learning_objectives text NOT NULL,
 difficulty varchar(30) NOT NULL CHECK(difficulty IN ('INTRODUCTORY','INTERMEDIATE','ADVANCED')),
 estimated_minutes integer NOT NULL CHECK(estimated_minutes>0), translations jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(translations)='object'),
 provenance jsonb NOT NULL CHECK(jsonb_typeof(provenance)='object'), content_hash varchar(64) CHECK(content_hash ~ '^[0-9a-f]{64}$'),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, published_at timestamptz,
 row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0),
 CONSTRAINT uq_scenario_version_number UNIQUE(scenario_id,version_number), CONSTRAINT uq_scenario_version_parent UNIQUE(scenario_id,id),
 CONSTRAINT ck_scenario_version_publication CHECK((status='DRAFT' AND published_at IS NULL) OR (status='PUBLISHED' AND published_at IS NOT NULL AND content_hash IS NOT NULL))
);
ALTER TABLE public.scenario ADD CONSTRAINT fk_scenario_current FOREIGN KEY(id,current_version_id) REFERENCES public.scenario_version(scenario_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT;
CREATE INDEX ix_scenario_current ON public.scenario(id,current_version_id);
CREATE TABLE public.simulation_task (
