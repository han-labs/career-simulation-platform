 position integer NOT NULL CHECK(position>0), name varchar(180) NOT NULL, format varchar(32) NOT NULL CHECK(format IN ('TEXT','URL','FILE','JSON')),
 required boolean NOT NULL DEFAULT true, validation_config jsonb NOT NULL CHECK(jsonb_typeof(validation_config)='object'),
 CONSTRAINT uq_task_deliverable_definition_position UNIQUE(task_id,position), CONSTRAINT uq_task_deliverable_definition_task UNIQUE(id,task_id)
);
CREATE TABLE public.task_resource (
