 scenario_version_id bigint NOT NULL REFERENCES public.scenario_version ON DELETE RESTRICT ON UPDATE RESTRICT,
 status varchar(32) NOT NULL DEFAULT 'ENROLLED' CHECK(status IN ('ENROLLED','IN_PROGRESS','COMPLETED')),
 enrolled_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, started_at timestamptz, completed_at timestamptz,
 row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0),
