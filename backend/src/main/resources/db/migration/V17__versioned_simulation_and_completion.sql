CREATE FUNCTION public.core_guard_scenario_content() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE o jsonb; n jsonb; p bigint; s text; versions bigint[]; BEGIN
 o=CASE WHEN TG_OP<>'INSERT' THEN to_jsonb(OLD) ELSE '{}'::jsonb END;
 n=CASE WHEN TG_OP<>'DELETE' THEN to_jsonb(NEW) ELSE '{}'::jsonb END;
 IF TG_TABLE_NAME='simulation_task' THEN
  versions=ARRAY[(o->>'scenario_version_id')::bigint,(n->>'scenario_version_id')::bigint];
 ELSE
  SELECT array_agg(DISTINCT scenario_version_id ORDER BY scenario_version_id) INTO versions FROM public.simulation_task WHERE id IN ((o->>'task_id')::bigint,(n->>'task_id')::bigint);
 END IF;
 FOR p IN SELECT DISTINCT x FROM unnest(versions) x WHERE x IS NOT NULL ORDER BY x LOOP
  SELECT status INTO s FROM public.scenario_version WHERE id=p FOR UPDATE;
  IF s='PUBLISHED' THEN RAISE EXCEPTION 'PUBLISHED_SCENARIO_CONTENT_IMMUTABLE' USING ERRCODE='23514'; END IF;
 END LOOP;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER guard_scenario_version BEFORE UPDATE OR DELETE ON public.scenario_version FOR EACH ROW EXECUTE FUNCTION public.core_version_immutable();
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['simulation_task','task_deliverable_definition','task_resource','model_answer','task_skill'] LOOP
  EXECUTE format('CREATE TRIGGER guard_content BEFORE INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.core_guard_scenario_content()',t);
 END LOOP;
END $$;
CREATE FUNCTION public.core_guard_final_submission() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF OLD.status='FINAL' THEN RAISE EXCEPTION 'FINAL_SUBMISSION_IMMUTABLE' USING ERRCODE='23514'; END IF;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER guard_final_submission BEFORE UPDATE OR DELETE ON public.task_submission FOR EACH ROW EXECUTE FUNCTION public.core_guard_final_submission();
CREATE FUNCTION public.core_guard_submitted_deliverable() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE p bigint; e bigint; s text; BEGIN
 FOR p IN SELECT DISTINCT x FROM unnest(ARRAY[CASE WHEN TG_OP<>'INSERT' THEN OLD.submission_id END,CASE WHEN TG_OP<>'DELETE' THEN NEW.submission_id END]) x WHERE x IS NOT NULL ORDER BY x LOOP
  SELECT enrollment_id INTO e FROM public.task_submission WHERE id=p;
  PERFORM id FROM public.simulation_enrollment WHERE id=e FOR UPDATE;
  SELECT status INTO s FROM public.task_submission WHERE id=p FOR UPDATE;
  IF s='FINAL' THEN RAISE EXCEPTION 'FINAL_DELIVERABLE_IMMUTABLE' USING ERRCODE='23514'; END IF;
 END LOOP;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER guard_submitted_deliverable BEFORE INSERT OR UPDATE OR DELETE ON public.submitted_deliverable FOR EACH ROW EXECUTE FUNCTION public.core_guard_submitted_deliverable();
CREATE TRIGGER guard_simulation_completion BEFORE UPDATE OR DELETE ON public.simulation_completion FOR EACH ROW EXECUTE FUNCTION public.core_history_immutable();
CREATE FUNCTION public.core_guard_ready_asset() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF OLD.state IN ('READY','REDACTED') AND (TG_OP='DELETE' OR (to_jsonb(NEW)-'state'-'row_version') IS DISTINCT FROM (to_jsonb(OLD)-'state'-'row_version') OR NEW.state NOT IN ('READY','REDACTED')) THEN
  RAISE EXCEPTION 'READY_ASSET_BYTES_IMMUTABLE' USING ERRCODE='23514';
 END IF;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER guard_ready_asset BEFORE UPDATE OR DELETE ON public.file_asset FOR EACH ROW EXECUTE FUNCTION public.core_guard_ready_asset();

-- Stable, schema-unique names for column-level FK/CHECK declarations.
DO $$ DECLARE c record; n text; BEGIN
 FOR c IN SELECT k.oid,k.conname,k.contype,t.relname,
  COALESCE((SELECT string_agg(a.attname,'_' ORDER BY u.ordinality) FROM unnest(k.conkey) WITH ORDINALITY u(attnum,ordinality) JOIN pg_attribute a ON a.attrelid=k.conrelid AND a.attnum=u.attnum),'rule') AS columns
  FROM pg_constraint k JOIN pg_class t ON t.oid=k.conrelid JOIN pg_namespace s ON s.oid=t.relnamespace
  WHERE s.nspname='public' AND t.relname IN ('scenario','scenario_version','simulation_task','task_deliverable_definition','task_resource','model_answer','career_skill','task_skill','simulation_enrollment','task_submission','submitted_deliverable','simulation_completion') AND k.contype IN ('f','c')
   AND k.conname NOT LIKE 'fk\_%' ESCAPE '\' AND k.conname NOT LIKE 'ck\_%' ESCAPE '\'
 LOOP
  n=CASE c.contype WHEN 'f' THEN 'fk_' ELSE 'ck_' END || left(c.relname,30)||'_'||left(c.columns,20)||'_'||left(md5(pg_get_constraintdef(c.oid)),6);
  EXECUTE format('ALTER TABLE public.%I RENAME CONSTRAINT %I TO %I',c.relname,c.conname,n);
 END LOOP;
END $$;