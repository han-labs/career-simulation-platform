CREATE TABLE public.enterprise (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_enterprise PRIMARY KEY,
 name varchar(240) NOT NULL CONSTRAINT ck_enterprise_name CHECK(length(btrim(name))>0),
 verification_status varchar(32) NOT NULL DEFAULT 'PENDING' CHECK(verification_status IN ('PENDING','VERIFIED','REJECTED')),
 publishing_status varchar(32) NOT NULL DEFAULT 'DISABLED' CHECK(publishing_status IN ('DISABLED','ENABLED','SUSPENDED')),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0)
);
CREATE TABLE public.enterprise_representative (
 user_id bigint CONSTRAINT pk_enterprise_representative PRIMARY KEY REFERENCES public.app_users ON DELETE RESTRICT ON UPDATE RESTRICT,
 enterprise_id bigint NOT NULL REFERENCES public.enterprise ON DELETE RESTRICT ON UPDATE RESTRICT,
 membership_status varchar(32) NOT NULL DEFAULT 'ACTIVE' CHECK(membership_status IN ('ACTIVE','SUSPENDED')),
 publishing_permission boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0)
);
CREATE INDEX ix_enterprise_representative_enterprise ON public.enterprise_representative(enterprise_id);
CREATE TABLE public.consent_grant (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_consent_grant PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES public.app_users ON DELETE RESTRICT ON UPDATE RESTRICT,
 purpose varchar(32) NOT NULL CHECK(purpose IN ('PROFILE_SHARE','COMPLETION_SHARE','SUBMISSION_SHARE','ASSESSMENT_SHARE','EXTERNAL_AI','LONG_TERM_MEMORY','RECRUITMENT_CONTACT')),
 enterprise_id bigint REFERENCES public.enterprise ON DELETE RESTRICT ON UPDATE RESTRICT,
 recipient_key varchar(180) NOT NULL, policy_version varchar(80) NOT NULL,
 confirmed_at timestamptz NOT NULL, revoked_at timestamptz, expires_at timestamptz,
 confirmation_method varchar(32) NOT NULL CHECK(confirmation_method='EXPLICIT_UI'),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_consent_grant_owner UNIQUE(id,user_id),
 CONSTRAINT ck_consent_grant_dates CHECK((revoked_at IS NULL OR revoked_at>=confirmed_at) AND (expires_at IS NULL OR expires_at>=confirmed_at)),
 CONSTRAINT ck_consent_grant_recipient CHECK(
  (purpose IN ('PROFILE_SHARE','COMPLETION_SHARE','SUBMISSION_SHARE','ASSESSMENT_SHARE','RECRUITMENT_CONTACT') AND enterprise_id IS NOT NULL AND recipient_key='enterprise:'||enterprise_id::text)
  OR (purpose='EXTERNAL_AI' AND enterprise_id IS NULL AND recipient_key LIKE 'provider:%')
  OR (purpose='LONG_TERM_MEMORY' AND enterprise_id IS NULL AND recipient_key='platform-memory'))
);
CREATE UNIQUE INDEX uq_consent_grant_current ON public.consent_grant(user_id,purpose,recipient_key) WHERE revoked_at IS NULL;
CREATE INDEX ix_consent_grant_owner_time ON public.consent_grant(user_id,purpose,confirmed_at DESC);
CREATE INDEX ix_consent_grant_enterprise ON public.consent_grant(enterprise_id);
CREATE TABLE public.audit_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_audit_event PRIMARY KEY,
 actor_user_id bigint REFERENCES public.app_users ON DELETE RESTRICT ON UPDATE RESTRICT,
 action varchar(100) NOT NULL, target_type varchar(80) NOT NULL, target_key varchar(100) NOT NULL,
 detail jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(detail)='object'),
 occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, correlation_id uuid
);
CREATE INDEX ix_audit_event_target ON public.audit_event(target_type,target_key,occurred_at);
CREATE INDEX ix_audit_event_actor ON public.audit_event(actor_user_id,occurred_at DESC);
CREATE TABLE public.migration_record (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_migration_record PRIMARY KEY,
 source_table varchar(80) NOT NULL, source_key varchar(180) NOT NULL,
 target_table varchar(80), target_key varchar(180),
 source_hash varchar(64) NOT NULL CHECK(source_hash ~ '^[0-9a-f]{64}$'),
 state varchar(32) NOT NULL CHECK(state IN ('PENDING','MAPPED','PRESERVED','CONFLICT')),
 reason_code varchar(100) NOT NULL,
 reviewed_by bigint REFERENCES public.app_users ON DELETE RESTRICT ON UPDATE RESTRICT,
 reviewed_at timestamptz, details jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(details)='object'),
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_migration_record_source UNIQUE(source_table,source_key),
 CONSTRAINT ck_migration_record_target CHECK((target_table IS NULL)=(target_key IS NULL) AND (state<>'MAPPED' OR target_key IS NOT NULL))
);
CREATE INDEX ix_migration_record_state ON public.migration_record(state,id);
CREATE INDEX ix_migration_record_reviewer ON public.migration_record(reviewed_by);

-- Stable, schema-unique names for column-level FK/CHECK declarations.
DO $$ DECLARE c record; n text; BEGIN
 FOR c IN SELECT k.oid,k.conname,k.contype,t.relname,
  COALESCE((SELECT string_agg(a.attname,'_' ORDER BY u.ordinality) FROM unnest(k.conkey) WITH ORDINALITY u(attnum,ordinality) JOIN pg_attribute a ON a.attrelid=k.conrelid AND a.attnum=u.attnum),'rule') AS columns
  FROM pg_constraint k JOIN pg_class t ON t.oid=k.conrelid JOIN pg_namespace s ON s.oid=t.relnamespace
  WHERE s.nspname='public' AND t.relname IN ('enterprise','enterprise_representative','consent_grant','audit_event','migration_record') AND k.contype IN ('f','c')
   AND k.conname NOT LIKE 'fk\_%' ESCAPE '\' AND k.conname NOT LIKE 'ck\_%' ESCAPE '\'
 LOOP
  n=CASE c.contype WHEN 'f' THEN 'fk_' ELSE 'ck_' END || left(c.relname,30)||'_'||left(c.columns,20)||'_'||left(md5(pg_get_constraintdef(c.oid)),6);
  EXECUTE format('ALTER TABLE public.%I RENAME CONSTRAINT %I TO %I',c.relname,c.conname,n);
 END LOOP;
END $$;
