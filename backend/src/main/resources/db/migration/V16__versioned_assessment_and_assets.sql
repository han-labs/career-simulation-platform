CREATE TABLE public.file_asset (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_file_asset PRIMARY KEY,
 owner_user_id bigint NOT NULL REFERENCES public.app_users ON DELETE RESTRICT ON UPDATE RESTRICT,
 enterprise_id bigint REFERENCES public.enterprise ON DELETE RESTRICT ON UPDATE RESTRICT,
 storage_key varchar(512) NOT NULL CONSTRAINT uq_file_asset_storage UNIQUE,
 original_name varchar(255) NOT NULL, mime_type varchar(120) NOT NULL,
 size_bytes bigint NOT NULL CHECK(size_bytes>=0), checksum varchar(64) NOT NULL CHECK(checksum ~ '^[0-9a-f]{64}$'),
 state varchar(32) NOT NULL DEFAULT 'STAGED' CHECK(state IN ('STAGED','READY','REJECTED','REDACTED')),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, ready_at timestamptz,
 row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0),
 CONSTRAINT ck_file_asset_ready CHECK(state<>'READY' OR ready_at IS NOT NULL)
);
CREATE INDEX ix_file_asset_owner ON public.file_asset(owner_user_id);
CREATE INDEX ix_file_asset_enterprise ON public.file_asset(enterprise_id);
CREATE TABLE public.assessment_type (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_assessment_type PRIMARY KEY,
 code varchar(80) NOT NULL CONSTRAINT uq_assessment_type_code UNIQUE, name varchar(160) NOT NULL,
 status varchar(32) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','ARCHIVED')), active_version_id bigint,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0)
);
CREATE TABLE public.assessment_version (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_assessment_version PRIMARY KEY,
 assessment_type_id bigint NOT NULL REFERENCES public.assessment_type ON DELETE RESTRICT ON UPDATE RESTRICT,
 version_number integer NOT NULL CHECK(version_number>0),
 status varchar(32) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PUBLISHED')),
 evaluator_key varchar(100) NOT NULL, evaluator_version varchar(80) NOT NULL,
 scoring_config jsonb NOT NULL CHECK(jsonb_typeof(scoring_config)='object'),
 content_hash varchar(64) CHECK(content_hash ~ '^[0-9a-f]{64}$'),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, published_at timestamptz,
 row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0),
 CONSTRAINT uq_assessment_version_number UNIQUE(assessment_type_id,version_number),
 CONSTRAINT uq_assessment_version_parent UNIQUE(assessment_type_id,id),
 CONSTRAINT ck_assessment_version_publication CHECK((status='DRAFT' AND published_at IS NULL) OR (status='PUBLISHED' AND published_at IS NOT NULL AND content_hash IS NOT NULL))
);
ALTER TABLE public.assessment_type ADD CONSTRAINT fk_assessment_type_current FOREIGN KEY(id,active_version_id)
 REFERENCES public.assessment_version(assessment_type_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT;
CREATE INDEX ix_assessment_type_current ON public.assessment_type(id,active_version_id);
CREATE TABLE public.assessment_question (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_assessment_question PRIMARY KEY,
 assessment_version_id bigint NOT NULL REFERENCES public.assessment_version ON DELETE RESTRICT ON UPDATE RESTRICT,
 position integer NOT NULL CHECK(position>0), prompt text NOT NULL,
 response_type varchar(32) NOT NULL CHECK(response_type IN ('LIKERT','CHOICE','TEXT')),
 response_config jsonb NOT NULL CHECK(jsonb_typeof(response_config)='object'),
 translations jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(translations)='object'), required boolean NOT NULL DEFAULT true,
 CONSTRAINT uq_assessment_question_position UNIQUE(assessment_version_id,position),
 CONSTRAINT uq_assessment_question_version UNIQUE(id,assessment_version_id)
);
CREATE TABLE public.assessment_attempt (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_assessment_attempt PRIMARY KEY,
 student_id bigint NOT NULL REFERENCES public.student_profiles(user_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 assessment_version_id bigint NOT NULL REFERENCES public.assessment_version ON DELETE RESTRICT ON UPDATE RESTRICT,
 status varchar(32) NOT NULL DEFAULT 'IN_PROGRESS' CHECK(status IN ('IN_PROGRESS','SUBMITTED')),
 start_request_id uuid NOT NULL, started_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 submitted_at timestamptz, final_payload_hash varchar(64) CHECK(final_payload_hash ~ '^[0-9a-f]{64}$'),
 row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0),
 CONSTRAINT uq_assessment_attempt_request UNIQUE(student_id,start_request_id),
 CONSTRAINT uq_assessment_attempt_version UNIQUE(id,assessment_version_id),
 CONSTRAINT ck_assessment_attempt_final CHECK((status='IN_PROGRESS' AND submitted_at IS NULL AND final_payload_hash IS NULL) OR (status='SUBMITTED' AND submitted_at IS NOT NULL AND final_payload_hash IS NOT NULL))
);
CREATE INDEX ix_assessment_attempt_student ON public.assessment_attempt(student_id,started_at DESC,id);
CREATE INDEX ix_assessment_attempt_version ON public.assessment_attempt(assessment_version_id);
CREATE TABLE public.assessment_response (
 attempt_id bigint NOT NULL, question_id bigint NOT NULL, assessment_version_id bigint NOT NULL,
 answer_data jsonb NOT NULL CHECK(jsonb_typeof(answer_data)='object'), updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT pk_assessment_response PRIMARY KEY(attempt_id,question_id),
 CONSTRAINT fk_assessment_response_attempt FOREIGN KEY(attempt_id,assessment_version_id) REFERENCES public.assessment_attempt(id,assessment_version_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_assessment_response_question FOREIGN KEY(question_id,assessment_version_id) REFERENCES public.assessment_question(id,assessment_version_id) ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX ix_assessment_response_attempt ON public.assessment_response(attempt_id,assessment_version_id);
CREATE INDEX ix_assessment_response_question ON public.assessment_response(question_id,assessment_version_id);
CREATE TABLE public.assessment_result (
 attempt_id bigint CONSTRAINT pk_assessment_result PRIMARY KEY REFERENCES public.assessment_attempt ON DELETE RESTRICT ON UPDATE RESTRICT,
 result_data jsonb NOT NULL CHECK(jsonb_typeof(result_data)='object'), evaluator_key varchar(100) NOT NULL,
 evaluator_version varchar(80) NOT NULL, input_hash varchar(64) NOT NULL CHECK(input_hash ~ '^[0-9a-f]{64}$'),
 calculated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE FUNCTION public.core_history_immutable() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 RAISE EXCEPTION 'IMMUTABLE_HISTORY: %', TG_TABLE_NAME USING ERRCODE='23514';
END $$;
CREATE FUNCTION public.core_version_immutable() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF OLD.status='PUBLISHED' THEN RAISE EXCEPTION 'PUBLISHED_CONTENT_IMMUTABLE: %', TG_TABLE_NAME USING ERRCODE='23514'; END IF;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER guard_assessment_version BEFORE UPDATE OR DELETE ON public.assessment_version FOR EACH ROW EXECUTE FUNCTION public.core_version_immutable();
CREATE FUNCTION public.core_guard_assessment_question() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE p bigint; s text; BEGIN
 FOR p IN SELECT DISTINCT x FROM unnest(ARRAY[CASE WHEN TG_OP<>'INSERT' THEN OLD.assessment_version_id END,CASE WHEN TG_OP<>'DELETE' THEN NEW.assessment_version_id END]) x WHERE x IS NOT NULL ORDER BY x LOOP
  SELECT status INTO s FROM public.assessment_version WHERE id=p FOR UPDATE;
  IF s='PUBLISHED' THEN RAISE EXCEPTION 'PUBLISHED_QUESTION_IMMUTABLE' USING ERRCODE='23514'; END IF;
 END LOOP;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER guard_assessment_question BEFORE INSERT OR UPDATE OR DELETE ON public.assessment_question FOR EACH ROW EXECUTE FUNCTION public.core_guard_assessment_question();
CREATE FUNCTION public.core_guard_assessment_response() RETURNS trigger LANGUAGE plpgsql AS $$ DECLARE p bigint; s text; BEGIN
 FOR p IN SELECT DISTINCT x FROM unnest(ARRAY[CASE WHEN TG_OP<>'INSERT' THEN OLD.attempt_id END,CASE WHEN TG_OP<>'DELETE' THEN NEW.attempt_id END]) x WHERE x IS NOT NULL ORDER BY x LOOP
  SELECT status INTO s FROM public.assessment_attempt WHERE id=p FOR UPDATE;
  IF s='SUBMITTED' THEN RAISE EXCEPTION 'SUBMITTED_RESPONSE_IMMUTABLE' USING ERRCODE='23514'; END IF;
 END LOOP;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER guard_assessment_response BEFORE INSERT OR UPDATE OR DELETE ON public.assessment_response FOR EACH ROW EXECUTE FUNCTION public.core_guard_assessment_response();
CREATE TRIGGER guard_assessment_result BEFORE UPDATE OR DELETE ON public.assessment_result FOR EACH ROW EXECUTE FUNCTION public.core_history_immutable();
CREATE FUNCTION public.core_guard_assessment_attempt() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF OLD.status='SUBMITTED' THEN RAISE EXCEPTION 'SUBMITTED_ATTEMPT_IMMUTABLE' USING ERRCODE='23514'; END IF;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER guard_assessment_attempt BEFORE UPDATE OR DELETE ON public.assessment_attempt FOR EACH ROW EXECUTE FUNCTION public.core_guard_assessment_attempt();

-- Stable, schema-unique names for column-level FK/CHECK declarations.
DO $$ DECLARE c record; n text; BEGIN
 FOR c IN SELECT k.oid,k.conname,k.contype,t.relname,
  COALESCE((SELECT string_agg(a.attname,'_' ORDER BY u.ordinality) FROM unnest(k.conkey) WITH ORDINALITY u(attnum,ordinality) JOIN pg_attribute a ON a.attrelid=k.conrelid AND a.attnum=u.attnum),'rule') AS columns
  FROM pg_constraint k JOIN pg_class t ON t.oid=k.conrelid JOIN pg_namespace s ON s.oid=t.relnamespace
  WHERE s.nspname='public' AND t.relname IN ('file_asset','assessment_type','assessment_version','assessment_question','assessment_attempt','assessment_response','assessment_result') AND k.contype IN ('f','c')
   AND k.conname NOT LIKE 'fk\_%' ESCAPE '\' AND k.conname NOT LIKE 'ck\_%' ESCAPE '\'
 LOOP
  n=CASE c.contype WHEN 'f' THEN 'fk_' ELSE 'ck_' END || left(c.relname,30)||'_'||left(c.columns,20)||'_'||left(md5(pg_get_constraintdef(c.oid)),6);
  EXECUTE format('ALTER TABLE public.%I RENAME CONSTRAINT %I TO %I',c.relname,c.conname,n);
 END LOOP;
END $$;