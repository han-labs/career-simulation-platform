CREATE TABLE public.exploration_plan (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_exploration_plan PRIMARY KEY,
 student_id bigint NOT NULL REFERENCES public.student_profiles(user_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 source_proposal_id uuid CONSTRAINT uq_exploration_plan_proposal UNIQUE,
 title varchar(120) NOT NULL, steps jsonb NOT NULL CHECK(jsonb_typeof(steps)='array'),
 status varchar(32) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','ARCHIVED')),
 confirmed_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0 CHECK(row_version>=0)
);
-- Reserved nullable proposal identity. The real FK is deliberately deferred to Package B/V18.
CREATE UNIQUE INDEX uq_exploration_plan_active ON public.exploration_plan(student_id) WHERE status='ACTIVE';
CREATE INDEX ix_exploration_plan_student ON public.exploration_plan(student_id,confirmed_at DESC,id);
