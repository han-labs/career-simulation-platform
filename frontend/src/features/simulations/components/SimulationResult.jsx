import { useI18n } from '../../../shared/i18n/useI18n.js'
// Renders objective outcomes after evaluation; this component is never mounted before submit.
import { CheckCircle2, CircleX } from 'lucide-react'

function SimulationResult({ result, onRestart }) {
  const { t, locale } = useI18n()
  return (
    <section className="simulation-result" aria-labelledby="result-title" tabIndex="-1">
      <p className="eyebrow">{t("Objective result")}</p>
      <h2 id="result-title">{t(result.correctCount)} {t("of")} {t(result.totalTasks)} {t("tasks correct")}</h2>
      <p className="result-score">{t(result.percentage)}%</p>
      <p>{t("These outcomes are generated by deterministic mock rules for this Phase 1 interface.")}</p>
      <ol className="outcome-list">
        {result.outcomes.map((outcome) => (
          <li className="outcome-item" key={outcome.taskId}>
            {outcome.isCorrect
              ? <CheckCircle2 aria-hidden="true" size={22} />
              : <CircleX aria-hidden="true" size={22} />}
            <div>
              <h3>{t(outcome.title)}</h3>
              <p><strong>{t(outcome.isCorrect ? 'Correct.' : 'Needs review.')}</strong> {locale === 'vi' && outcome.explanationVi ? outcome.explanationVi : t(outcome.explanation)}</p>
            </div>
          </li>
        ))}
      </ol>
      <button className="button button--secondary" type="button" onClick={onRestart}> {t("Try again")} </button>
    </section>
  )
}

export default SimulationResult
