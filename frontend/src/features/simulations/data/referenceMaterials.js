// Supplemental display links do not mutate sealed ScenarioVersions or enrollment history.
export function taskReferenceMaterials(metadata, task, finalized = false) {
  const stored = task?.resources ?? []
  const visible = stored.filter(resource => resource.releasePolicy === 'TASK_ACCESS' || finalized)
  if (!task || !metadata) return visible
  // Enrollment's public metadata omits provenance. Match its original fields, not a route slug
  // or database IDs, so resumed/pinned enrollments and translated UI use the same references.
  const program = materials.find(entry => entry.title === metadata.title && entry.targetRole === metadata.targetRole && entry.careerTrack === metadata.careerTrack)
  const selected = program?.tasks[task.title] ?? []
  // Reserve even hidden URLs: a supplement must never release a gated server resource early.
  const known = new Set(stored.map(resource => resource.externalUrl).filter(Boolean))
  const extra = selected.filter(resource => {
    if (known.has(resource.externalUrl)) return false
    known.add(resource.externalUrl)
    return true
  }).map(resource => ({ ...resource, id: `reference:${resource.externalUrl}`, releasePolicy: 'TASK_ACCESS' }))
  return [...visible, ...extra]
}
